const localeSelect = document.querySelector('#language');
const supportedLanguages = ['ru', 'en', 'pl'];
const languageKey = 'smith-language';

function initialLanguage() {
  try {
    const saved = localStorage.getItem(languageKey);
    if (supportedLanguages.includes(saved)) return saved;
  } catch {}
  return (navigator.languages?.length ? navigator.languages : [navigator.language])
    .map(tag => tag?.split('-')[0].toLowerCase())
    .find(code => supportedLanguages.includes(code)) ?? 'ru';
}

let language = initialLanguage();

function t(source, values = {}) {
  const localized = translations[source]?.[language] ?? source;
  return localized.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

// Keep the original Russian text and translate only known strings.
// Text node updates preserve links, form controls and their current values.
const staticMessages = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
for (let node = walker.nextNode(); node; node = walker.nextNode()) {
  const original = node.nodeValue.trim();
  if (Object.hasOwn(translations, original)) {
    const [leading] = node.nodeValue.match(/^\s*/);
    const [trailing] = node.nodeValue.match(/\s*$/);
    staticMessages.push(() => { node.nodeValue = leading + t(original) + trailing; });
  }
}
for (const attribute of ['aria-label', 'alt', 'title']) {
  for (const element of document.querySelectorAll('[' + attribute + ']')) {
    const original = element.getAttribute(attribute);
    if (Object.hasOwn(translations, original)) {
      staticMessages.push(() => element.setAttribute(attribute, t(original)));
    }
  }
}
const originalTitle = document.title;
const description = document.querySelector('meta[name="description"]');
const originalDescription = description.content;

function translatePage() {
  document.documentElement.lang = language;
  document.title = t(originalTitle);
  description.content = t(originalDescription);
  localeSelect.value = language;
  staticMessages.forEach(render => render());
}

localeSelect.addEventListener('change', () => {
  language = localeSelect.value;
  try { localStorage.setItem(languageKey, language); } catch {}
  translatePage();
  document.dispatchEvent(new Event('guide-language-change'));
});
translatePage();
